errors = []
def check(text, limit, what):
    if len(text) > limit:
        errors.append(f'{what}: {len(text)}>{limit}: {text}')

for c in campaigns:
    for g in c['groups']:
        common = COMMON[c['common']]
        g['headlines'] = list(dict.fromkeys(g['headlines'] + common['h']))[:15]
        g['descriptions'] = (g['descriptions'] + common['d'])[:4]
        for text in g['headlines'] + g['descriptions']:
            if any(ch.isdigit() for ch in text) and ('707' in text or '777' in text):
                errors.append(f'телефон в тексте: {text}')
        for h in g['headlines']: check(h, 30, f"H {g['name']}")
        for d in g['descriptions']: check(d, 90, f"D {g['name']}")
        for p in g['path']: check(p, 15, f"path {g['name']}")
        if len(g['headlines']) < 10: errors.append(f"мало заголовков в {g['name']}: {len(g['headlines'])}")
